import fs from 'node:fs/promises';
import path from 'node:path';

const ua =
  'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/124.0.0.0 Safari/537.36';
const cssUrl =
  'https://fonts.googleapis.com/css2?family=DM+Serif+Display:ital@0;1&family=Inter:wght@300..700&display=swap';

const css = await fetch(cssUrl, { headers: { 'User-Agent': ua } }).then((r) => r.text());
const outDir = path.resolve('public/fonts');
await fs.mkdir(outDir, { recursive: true });

// Split into `/* subset */ @font-face {...}` groups and keep latin + latin-ext.
const groups = css.split(/\/\*\s*([a-z-]+)\s*\*\//i).slice(1);
const faces = [];
for (let i = 0; i < groups.length; i += 2) {
  const subset = groups[i];
  const block = groups[i + 1];
  if (subset !== 'latin') continue;
  const family = /font-family: '([^']+)'/.exec(block)?.[1];
  const style = /font-style: (\w+)/.exec(block)?.[1];
  const weight = /font-weight: ([\d ]+)/.exec(block)?.[1]?.trim();
  const url = /url\((https:[^)]+)\)/.exec(block)?.[1];
  const range = /unicode-range: ([^;]+);/.exec(block)?.[1];
  if (!family || !url) continue;
  const slug = `${family.toLowerCase().replace(/[^a-z]+/g, '-')}-${style}-${weight?.replace(/\s+/g, '-')}`;
  const file = `${slug}.woff2`;
  const res = await fetch(url, { headers: { 'User-Agent': ua } });
  if (!res.ok) throw new Error(`font ${file} ${res.status}`);
  await fs.writeFile(path.join(outDir, file), Buffer.from(await res.arrayBuffer()));
  faces.push({ family, style, weight, file, range });
  console.log('↓', file);
}

const cssOut = faces
  .map(
    (f) => `@font-face {
  font-family: '${f.family}';
  font-style: ${f.style};
  font-weight: ${f.weight};
  font-display: swap;
  src: url('/fonts/${f.file}') format('woff2');
  unicode-range: ${f.range};
}`,
  )
  .join('\n\n');

await fs.writeFile('src/styles/fonts.css', `/* Self-hosted latin subsets — generated by scripts/fetch-fonts.mjs */\n\n${cssOut}\n`);
console.log('✓ fonts ready');
